// Generates, from docs/RF-07-diagnosis-content-and-pdf-generation/content-source.json:
//   - supabase/migrations/20260101000011_seed_content_v1.sql  (the seed of content version 1)
//   - docs/RF-07-diagnosis-content-and-pdf-generation/content-source.md  (readable copy for Millena's review)
// Run: node scripts/generate-content-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const DOCS = "docs/RF-07-diagnosis-content-and-pdf-generation";
const content = JSON.parse(readFileSync(`${DOCS}/content-source.json`, "utf8"));
const STYLES = ["esportivo_natural", "tradicional", "elegante", "romantico", "criativo", "dramatico"];
const LABELS = {
  esportivo_natural: "Esportivo/Natural",
  tradicional: "Tradicional",
  elegante: "Elegante",
  romantico: "Romântico",
  criativo: "Criativo",
  dramatico: "Dramático",
};

// --- checks: the seed must be complete before it is written ---
for (const style of STYLES) {
  const block = content.styles[style];
  for (const key of ["result", "secondary", "pieces_intro", "accessories_intro", "guidance"]) {
    if (!block?.[key]) throw new Error(`missing ${key} of ${style}`);
  }
  if (block.pieces?.length !== 8) throw new Error(`${style} needs 8 pieces`);
  if (block.accessories?.length !== 6) throw new Error(`${style} needs 6 accessories`);
  for (const other of STYLES) {
    if (other === style) continue;
    if (!content.pairs[`${style}|${other}`]) throw new Error(`missing pair ${style}|${other}`);
  }
}
if (Object.keys(content.pairs).length !== 30) throw new Error("expected 30 pair paragraphs");
// Migration 11 is released and never changes: its seed carries the texts of version 1 as they were. The
// text of a style when it is the secondary style (`secondary`) comes in migration 14.
const withoutSecondary = Object.fromEntries(
  Object.entries(content.styles).map(([style, block]) => [style, Object.fromEntries(Object.entries(block).filter(([key]) => key !== "secondary"))]),
);
const json = JSON.stringify({ styles: withoutSecondary, pairs: content.pairs }, null, 1);
if (json.includes("$json$")) throw new Error("content must not contain the dollar quote");

const sql = `-- RF-07: first content version (version 1), published.
-- Source: ${DOCS}/content-source.json (generated by scripts/generate-content-seed.mjs)
-- 6 style blocks x 4 kinds, 30 ordered-pair paragraphs, 8 pieces and 6 accessories per style = 138 templates.
-- The texts are a team draft (inferred): Millena reviews them and edits through the admin panel (RF-12),
-- which creates new versions; this migration never changes version 1.

do $seed$
declare
  v_id uuid;
  v_content jsonb := $json$${json}$json$;
  v_style text;
  v_block jsonb;
  v_pair record;
  v_item text;
  v_index integer;
begin
  insert into public.content_versions (version, status, published_at)
    values (1, 'published', now())
    returning id into v_id;

  for v_style, v_block in select key, value from jsonb_each(v_content -> 'styles') loop
    insert into public.content_templates (version_id, kind, style, block, position, body) values
      (v_id, 'style_block', v_style, 'result', 1, v_block ->> 'result'),
      (v_id, 'style_block', v_style, 'pieces', 1, v_block ->> 'pieces_intro'),
      (v_id, 'style_block', v_style, 'accessories', 1, v_block ->> 'accessories_intro'),
      (v_id, 'style_block', v_style, 'guidance', 1, v_block ->> 'guidance');

    v_index := 0;
    for v_item in select jsonb_array_elements_text(v_block -> 'pieces') loop
      v_index := v_index + 1;
      insert into public.content_templates (version_id, kind, style, position, body)
        values (v_id, 'piece', v_style, v_index, v_item);
    end loop;

    v_index := 0;
    for v_item in select jsonb_array_elements_text(v_block -> 'accessories') loop
      v_index := v_index + 1;
      insert into public.content_templates (version_id, kind, style, position, body)
        values (v_id, 'accessory', v_style, v_index, v_item);
    end loop;
  end loop;

  for v_pair in select key, value #>> '{}' as body from jsonb_each(v_content -> 'pairs') loop
    insert into public.content_templates (version_id, kind, style, secondary_style, position, body)
      values (v_id, 'pair_paragraph', split_part(v_pair.key, '|', 1), split_part(v_pair.key, '|', 2), 1, v_pair.body);
  end loop;
end
$seed$;
`;
writeFileSync("supabase/migrations/20260101000011_seed_content_v1.sql", sql, "utf8");

// --- migration 14: the text of a style when it is the secondary style ---
const secondaryRows = STYLES.map((style) => {
  const body = content.styles[style].secondary;
  if (body.includes("$json$") || body.includes("'")) throw new Error(`secondary text of ${style} has a quote`);
  return `    ('${style}', '${body}')`;
}).join(",\n");
const secondarySql = `-- RF-09 follow-up: the secondary style gets its own text.
-- The result text of a style is written for the predominant style ("o seu estilo predominante é o X"), and
-- it was also shown for the secondary one. The new block 'secondary' holds a text written for the second
-- style. Source: ${DOCS}/content-source.json (generated by scripts/generate-content-seed.mjs).
-- Migration 11 stays as released; this one adds the block to the check and the 6 texts to version 1.

alter table public.content_templates drop constraint content_templates_block_check;
alter table public.content_templates add constraint content_templates_block_check
  check (block in ('result', 'secondary', 'pieces', 'accessories', 'guidance'));

insert into public.content_templates (version_id, kind, style, block, position, body)
select v.id, 'style_block', t.style, 'secondary', 1, t.body
  from public.content_versions v
 cross join (values
${secondaryRows}
  ) as t(style, body)
 where v.version = 1;
`;
writeFileSync("supabase/migrations/20260101000014_secondary_style_text.sql", secondarySql, "utf8");

// --- readable copy for review ---
let md = `# Conteúdo do diagnóstico — versão 1 (rascunho da equipe)\n\n`;
md += `Fonte das migrations \`20260101000011_seed_content_v1.sql\` e \`20260101000014_secondary_style_text.sql\` (geradas por \`scripts/generate-content-seed.mjs\` a partir de \`content-source.json\`).\n\n`;
md += `**Rascunho da equipe (inferred).** A Millena revisa e edita estes textos pelo painel (RF-12). \`{nome}\` vira o primeiro nome da cliente.\n\n`;
for (const style of STYLES) {
  const b = content.styles[style];
  md += `## ${LABELS[style]}\n\n`;
  md += `**Resultado:** ${b.result}\n\n**Introdução das peças:** ${b.pieces_intro}\n\n**Introdução dos acessórios:** ${b.accessories_intro}\n\n**Orientação especial:** ${b.guidance}\n\n`;
  md += `**Peças (8):**\n${b.pieces.map((p, i) => `${i + 1}. ${p}`).join("\n")}\n\n`;
  md += `**Acessórios (6):**\n${b.accessories.map((p, i) => `${i + 1}. ${p}`).join("\n")}\n\n`;
}
md += `## Parágrafos de combinação (estilo predominante + secundário)\n\n`;
for (const first of STYLES) {
  for (const second of STYLES) {
    if (first === second) continue;
    md += `**${LABELS[first]} + ${LABELS[second]}:** ${content.pairs[`${first}|${second}`]}\n\n`;
  }
}
writeFileSync(`${DOCS}/content-source.md`, md, "utf8");
console.log("seed and readable copy written");
