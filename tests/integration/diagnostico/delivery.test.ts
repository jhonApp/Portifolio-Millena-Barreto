import { afterAll, afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { MAX_ATTACHMENT_BYTES, deliverDiagnosis, retryDelivery, runDueDeliveries, sendResultLinkEmail } from "@/lib/diagnostico/delivery";
import { DIAGNOSIS_BUCKET, diagnosisPdfPath } from "@/lib/diagnostico/diagnosis-storage";
import { generateDiagnosis } from "@/lib/diagnostico/generation";
import { loadResultByToken } from "@/lib/diagnostico/result-page";
import { findResultToken, mintResultToken } from "@/lib/diagnostico/result-token";
import { adminClient, createApprovedOrder, recordingEmailProvider } from "./helpers";

const db = adminClient();
const customerIds: string[] = [];
const orderIds: string[] = [];

const fakePdf = async () => new TextEncoder().encode("%PDF-1.4 fake");
const TOKEN = "T".repeat(43);

/** An order generated by the real RF-07 pipeline (fake PDF bytes), waiting for its delivery. */
async function generatedOrder(options: Parameters<typeof createApprovedOrder>[1] = {}) {
  const created = await createApprovedOrder(db, options);
  customerIds.push(created.customerId);
  orderIds.push(created.orderId);
  await generateDiagnosis(db, created.orderId, { deps: { renderPdf: fakePdf, onDiagnosisReady: async () => {} } });
  const { data: result } = await db.from("results").select("*").eq("order_id", created.orderId).single();
  const { data: customer } = await db.from("customers").select("email").eq("id", created.customerId).single();
  return { ...created, email: customer!.email, result: result! };
}

async function delivery(orderId: string) {
  const { data } = await db.from("deliveries").select("*").eq("order_id", orderId);
  return data ?? [];
}
async function orderRow(orderId: string) {
  const { data } = await db.from("orders").select("*").eq("id", orderId).single();
  return data!;
}
async function steps(orderId: string) {
  const { data } = await db.from("automation_errors").select("step, message, context").eq("order_id", orderId);
  return data ?? [];
}
async function tokenCount(orderId: string) {
  const { count } = await db.from("result_tokens").select("*", { count: "exact", head: true }).eq("order_id", orderId);
  return count ?? 0;
}
async function makeDue(orderId: string) {
  await db.from("deliveries").update({ next_attempt_at: new Date(Date.now() - 1000).toISOString() }).eq("order_id", orderId);
}
const linkOf = (html: string) => /href="([^"]*\/diagnostico-estilo\/resultado\/[^"]+)"/.exec(html)?.[1];

beforeEach(() => {
  vi.stubEnv("APP_URL", "http://localhost:3001");
});

afterEach(() => {
  vi.unstubAllEnvs();
  vi.restoreAllMocks();
});

afterAll(async () => {
  if (orderIds.length) {
    await db.storage.from(DIAGNOSIS_BUCKET).remove(orderIds.map(diagnosisPdfPath));
    await db.from("automation_errors").delete().in("order_id", orderIds);
  }
  if (customerIds.length) await db.from("customers").delete().in("id", customerIds);
});

describe("the diagnosis e-mail", () => {
  it("the e-mail has the subject the first name both styles the secure link and the PDF attached", async () => {
    const { orderId, email, result } = await generatedOrder({ name: "Maria Teste Silva" });
    const { provider, sent } = recordingEmailProvider();
    const outcome = await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider } });

    expect(outcome).toEqual({ result: "sent", orderId });
    expect(sent).toHaveLength(1);
    const message = sent[0];
    expect(message.to).toBe(email);
    expect(message.subject).toBe("Seu diagnóstico de estilo chegou!");
    const content = result.content as unknown as { predominant: { label: string }; secondary: { label: string } };
    for (const part of ["Maria", content.predominant.label, content.secondary.label]) {
      expect(message.html).toContain(part);
      expect(message.text).toContain(part);
    }
    expect(linkOf(message.html)).toBe(`http://localhost:3001/diagnostico-estilo/resultado/${TOKEN}`);
    expect(message.text).toContain(`http://localhost:3001/diagnostico-estilo/resultado/${TOKEN}`);
    expect(message.attachments).toHaveLength(1);
    expect(message.attachments![0].filename).toBe("diagnostico-de-estilo.pdf");
    expect(new TextDecoder().decode(message.attachments![0].content)).toBe("%PDF-1.4 fake");
  });

  it("a delivered order is DELIVERED and the delivery SENT", async () => {
    const { orderId } = await generatedOrder();
    await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider: recordingEmailProvider().provider } });
    const [row] = await delivery(orderId);
    expect(row).toMatchObject({ channel: "email", status: "SENT", attempts: 1, last_error: null });
    expect(row.sent_at).not.toBeNull();
    const order = await orderRow(orderId);
    expect(order.status).toBe("DELIVERED");
    expect(order.delivered_at).not.toBeNull();
  });

  it("the delivery row is created for the e-mail channel only", async () => {
    const { orderId } = await generatedOrder({ preference: "both" });
    await deliverDiagnosis(db, orderId, { deps: { provider: recordingEmailProvider().provider } });
    const rows = await delivery(orderId);
    expect(rows.map((r) => r.channel)).toEqual(["email"]);
  });

  it("a customer who chose whatsapp only still gets the e-mail", async () => {
    const { orderId } = await generatedOrder({ preference: "whatsapp" });
    const { provider, sent } = recordingEmailProvider();
    expect((await deliverDiagnosis(db, orderId, { deps: { provider } })).result).toBe("sent");
    expect(sent).toHaveLength(1);
    expect((await orderRow(orderId)).status).toBe("DELIVERED");
  });

  it("the e-mail goes to the registered address whatever the preference", async () => {
    for (const preference of ["email", "whatsapp", "both"] as const) {
      const { orderId, email } = await generatedOrder({ preference });
      const { provider, sent } = recordingEmailProvider();
      await deliverDiagnosis(db, orderId, { deps: { provider } });
      expect(sent.map((m) => m.to)).toEqual([email]);
    }
  });

  it("a token from RF-06 is used for the link on the first attempt", async () => {
    const { orderId } = await generatedOrder();
    const before = await tokenCount(orderId);
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider } });
    expect(linkOf(sent[0].html)).toContain(TOKEN);
    expect(await tokenCount(orderId)).toBe(before);
  });

  it("a null token gets a new token minted", async () => {
    const { orderId } = await generatedOrder();
    const before = await tokenCount(orderId);
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { token: null, deps: { provider } });
    expect(await tokenCount(orderId)).toBe(before + 1);
    const token = linkOf(sent[0].html)!.split("/").pop()!;
    expect(await findResultToken(db, token)).toEqual({ orderId });
  });
});

describe("attachments", () => {
  it("a PDF larger than 2 MB goes as a link only and the event is logged", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    const loadPdf = async () => new Uint8Array(MAX_ATTACHMENT_BYTES + 1);
    expect((await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider, loadPdf } })).result).toBe("sent");
    expect(sent[0].attachments).toBeUndefined();
    expect(linkOf(sent[0].html)).toContain(TOKEN);
    expect((await steps(orderId)).map((s) => s.step)).toContain("EMAIL_ATTACHMENT");
  });

  it("a PDF of exactly 2 MB is attached", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { deps: { provider, loadPdf: async () => new Uint8Array(MAX_ATTACHMENT_BYTES) } });
    expect(sent[0].attachments).toHaveLength(1);
  });

  it("a missing PDF goes as a link only", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    expect((await deliverDiagnosis(db, orderId, { deps: { provider, loadPdf: async () => null } })).result).toBe("sent");
    expect(sent[0].attachments).toBeUndefined();
    expect((await steps(orderId)).map((s) => s.step)).toContain("EMAIL_ATTACHMENT");
  });
});

describe("failures and retries", () => {
  it("a provider failure schedules a retry in 1 minute", async () => {
    const { orderId } = await generatedOrder();
    const outcome = await deliverDiagnosis(db, orderId, { deps: { provider: recordingEmailProvider({ fail: true }).provider } });
    expect(outcome.result).toBe("retry_scheduled");
    const seconds = (new Date((outcome as { nextAt: string }).nextAt).getTime() - Date.now()) / 1000;
    expect(seconds).toBeGreaterThan(55);
    expect(seconds).toBeLessThanOrEqual(61);
    const [row] = await delivery(orderId);
    expect(row).toMatchObject({ status: "PENDING", attempts: 1 });
    expect(row.last_error).toContain("EMAIL_UNAVAILABLE");
    expect((await orderRow(orderId)).status).toBe("PROCESSING");
  });

  it("the retries are scheduled at 1 5 and 15 minutes", async () => {
    const { orderId } = await generatedOrder();
    const { provider } = recordingEmailProvider({ fail: true });
    for (const minutes of [1, 5, 15]) {
      const outcome = await deliverDiagnosis(db, orderId, { deps: { provider } });
      expect(outcome.result).toBe("retry_scheduled");
      const seconds = (new Date((outcome as { nextAt: string }).nextAt).getTime() - Date.now()) / 1000;
      expect(seconds).toBeGreaterThan(minutes * 60 - 5);
      expect(seconds).toBeLessThanOrEqual(minutes * 60 + 1);
      await makeDue(orderId);
    }
  });

  it("after the third retry the delivery is FAILED the order FAILED and an automation error recorded", async () => {
    const { orderId } = await generatedOrder();
    const { provider } = recordingEmailProvider({ fail: true });
    for (let attempt = 1; attempt <= 3; attempt++) {
      expect((await deliverDiagnosis(db, orderId, { deps: { provider } })).result).toBe("retry_scheduled");
      await makeDue(orderId);
    }
    expect(await deliverDiagnosis(db, orderId, { deps: { provider } })).toEqual({ result: "failed", orderId });
    const [row] = await delivery(orderId);
    expect(row).toMatchObject({ status: "FAILED", attempts: 4, next_attempt_at: null });
    expect(await orderRow(orderId)).toMatchObject({ status: "FAILED", failure_reason: "DELIVERY_FAILED" });
    expect((await steps(orderId)).map((s) => s.step)).toContain("DELIVERY_FAILED");
  });

  it("the result can still be read after the delivery failed", async () => {
    const { orderId } = await generatedOrder();
    const { provider } = recordingEmailProvider({ fail: true });
    for (let attempt = 1; attempt <= 4; attempt++) {
      await deliverDiagnosis(db, orderId, { deps: { provider } });
      if (attempt < 4) await makeDue(orderId);
    }
    expect(await orderRow(orderId)).toMatchObject({ status: "FAILED", failure_reason: "DELIVERY_FAILED" });
    const state = await loadResultByToken(db, await mintResultToken(db, orderId));
    expect(state.state).toBe("ready");
  });

  it("a failed delivery is not sent again by the job", async () => {
    const { orderId, email } = await generatedOrder();
    const { provider, sent, state } = recordingEmailProvider({ fail: true });
    for (let attempt = 1; attempt <= 4; attempt++) {
      await deliverDiagnosis(db, orderId, { deps: { provider } });
      if (attempt < 4) await makeDue(orderId);
    }
    state.fail = false;
    const outcomes = await runDueDeliveries(db, { limit: 50, deps: { provider } });
    expect(outcomes.some((o) => o.orderId === orderId)).toBe(false);
    // Other orders of this file may be due; this customer must not receive anything.
    expect(sent.map((m) => m.to)).not.toContain(email);
  });

  it("a missing APP_URL fails as a retryable error naming the variable", async () => {
    const { orderId } = await generatedOrder();
    vi.stubEnv("APP_URL", "");
    const { provider, sent } = recordingEmailProvider();
    const outcome = await deliverDiagnosis(db, orderId, { deps: { provider } });
    expect(outcome.result).toBe("retry_scheduled");
    expect((await delivery(orderId))[0].last_error).toContain("APP_URL");
    expect(sent).toHaveLength(0);
  });

  it("no personal data in the delivery error records", async () => {
    const { orderId, email } = await generatedOrder({ name: "Fulana Sigilosa Pessoal" });
    const { provider } = recordingEmailProvider({ fail: true });
    for (let attempt = 1; attempt <= 4; attempt++) {
      await deliverDiagnosis(db, orderId, { deps: { provider } });
      if (attempt < 4) await makeDue(orderId);
    }
    const records = JSON.stringify([await delivery(orderId), await steps(orderId)]);
    expect(records).not.toContain("Fulana");
    expect(records).not.toContain(email);
    expect(records).not.toContain("@example.com");
    expect(records).not.toContain(TOKEN);
  });

  it("two overlapping runs send once", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider({ delayMs: 150 });
    const outcomes = await Promise.all([
      deliverDiagnosis(db, orderId, { deps: { provider } }),
      deliverDiagnosis(db, orderId, { deps: { provider } }),
    ]);
    expect(outcomes.map((o) => o.result).sort()).toEqual(["not_claimed", "sent"]);
    expect(sent).toHaveLength(1);
  });

  it("a delivered order is not sent again", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { deps: { provider } });
    expect((await deliverDiagnosis(db, orderId, { deps: { provider } })).result).toBe("already_sent");
    expect(sent).toHaveLength(1);
  });

  it("an order without a result is not claimed", async () => {
    const created = await createApprovedOrder(db);
    customerIds.push(created.customerId);
    orderIds.push(created.orderId);
    await db.from("orders").update({ status: "PROCESSING" }).eq("id", created.orderId);
    const { provider, sent } = recordingEmailProvider();
    expect((await deliverDiagnosis(db, created.orderId, { deps: { provider } })).result).toBe("not_claimed");
    expect(sent).toHaveLength(0);
  });
});

describe("due deliveries, retry and re-sent links", () => {
  it("runDueDeliveries sends a due retry and skips one that is not due", async () => {
    const due = await generatedOrder();
    const waiting = await generatedOrder();
    const failing = recordingEmailProvider({ fail: true }).provider;
    await deliverDiagnosis(db, due.orderId, { deps: { provider: failing } });
    await deliverDiagnosis(db, waiting.orderId, { deps: { provider: failing } });
    await makeDue(due.orderId);

    const { provider, sent } = recordingEmailProvider();
    const outcomes = await runDueDeliveries(db, { limit: 50, deps: { provider } });
    expect(outcomes.find((o) => o.orderId === due.orderId)?.result).toBe("sent");
    expect(outcomes.some((o) => o.orderId === waiting.orderId)).toBe(false);
    expect(sent.map((m) => m.to)).toContain(due.email);
    expect(sent.map((m) => m.to)).not.toContain(waiting.email);
  });

  it("runDueDeliveries picks a result older than a minute that never had a delivery", async () => {
    const { orderId, email } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    // Just saved: not stuck yet.
    expect((await runDueDeliveries(db, { limit: 50, deps: { provider } })).some((o) => o.orderId === orderId)).toBe(false);
    await db.from("results").update({ created_at: new Date(Date.now() - 5 * 60_000).toISOString() }).eq("order_id", orderId);
    const outcomes = await runDueDeliveries(db, { limit: 50, deps: { provider } });
    expect(outcomes.find((o) => o.orderId === orderId)?.result).toBe("sent");
    expect(sent.map((m) => m.to)).toContain(email);
    expect((await orderRow(orderId)).status).toBe("DELIVERED");
  });

  it("retryDelivery runs one send for a failed delivery", async () => {
    const { orderId } = await generatedOrder();
    const failing = recordingEmailProvider({ fail: true }).provider;
    for (let attempt = 1; attempt <= 4; attempt++) {
      await deliverDiagnosis(db, orderId, { deps: { provider: failing } });
      if (attempt < 4) await makeDue(orderId);
    }
    expect((await orderRow(orderId)).failure_reason).toBe("DELIVERY_FAILED");

    const { provider, sent } = recordingEmailProvider();
    expect((await retryDelivery(db, orderId, { deps: { provider } })).result).toBe("sent");
    expect(sent).toHaveLength(1);
    expect(await orderRow(orderId)).toMatchObject({ status: "DELIVERED", failure_reason: null });
    expect((await delivery(orderId))[0]).toMatchObject({ status: "SENT", attempts: 1 });
  });

  it("retryDelivery refuses a delivery that did not fail", async () => {
    const { orderId } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { deps: { provider } });
    expect((await retryDelivery(db, orderId, { deps: { provider } })).result).toBe("not_claimed");
    expect(sent).toHaveLength(1);
  });

  it("the result link e-mail does not change the delivery row", async () => {
    const { orderId, email } = await generatedOrder();
    const { provider, sent } = recordingEmailProvider();
    await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider } });
    const before = (await delivery(orderId))[0];
    const tokensBefore = await tokenCount(orderId);

    await sendResultLinkEmail(db, orderId, { deps: { provider } });
    expect(sent).toHaveLength(2);
    expect(sent[1].to).toBe(email);
    expect(linkOf(sent[1].html)).not.toContain(TOKEN); // a new token
    expect(await tokenCount(orderId)).toBe(tokensBefore + 1);
    const after = (await delivery(orderId))[0];
    expect(after).toMatchObject({ status: before.status, attempts: before.attempts, sent_at: before.sent_at, last_error: before.last_error });
    expect(await orderRow(orderId)).toMatchObject({ status: "DELIVERED" });
  });
});

describe("an order without an attempt (RF-09)", () => {
  it("an order without an attempt ends without a send", async () => {
    const { orderId } = await generatedOrder();
    // What is left of an order when its customer was erased: nobody to send to.
    await db.from("orders").update({ attempt_id: null }).eq("id", orderId);
    const { provider, sent } = recordingEmailProvider();
    const outcome = await deliverDiagnosis(db, orderId, { token: TOKEN, deps: { provider } });
    expect(outcome.result).toBe("retry_scheduled");
    expect(sent).toHaveLength(0);
  });
});

